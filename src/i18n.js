/**
 * The texts of one language.
 * @param {string} language `fr` or `en`; anything else falls back to French
 * @returns {object} the texts
 */
export function texts(language) {
  return TEXTS[language] || TEXTS[DEFAULT_LANGUAGE];
}

/**
 * Describe a Dreame error code for humans.
 * @param {number} code the ERROR property (2.2)
 * @param {string} language `fr` or `en`
 * @returns {string} a never-empty description
 */
export function describeError(code, language) {
  const t = texts(language);
  if (!code) {
    return t.noError;
  }
  return t.errors[code] || t.unknownError(code);
}
